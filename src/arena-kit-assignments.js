function assignmentKey(character) {
  return Number.isInteger(character.indexInElo) && character.eloId
    ? `${character.eloId}:${character.indexInElo}`
    : character.id;
}

export function attachArenaKitAssignment(character) {
  const key = assignmentKey(character);
  const assignment = arenaKitAssignments[key];
  if (!assignment) return character;
  const passiveName = character.passive?.name || assignment.pmaPassiveName || "Passiva";
  const passiveSynergy = `${passiveName} ${assignment.pmaPassiveHook}; isso sustenta a decisão central: ${assignment.pmaCombo}`;
  return {
    ...character,
    kitDesignReference: {
      ...assignment,
      pmaKey: key,
      adaptedLoop: assignment.pmaCombo,
      passiveSynergy,
      playerFacing: false
    },
    passive: character.passive
      ? { ...character.passive, kitSynergy: passiveSynergy }
      : character.passive
  };
}
